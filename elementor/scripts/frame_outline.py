#!/usr/bin/env python3
"""Print the CSS for the PES image/video frame shape (pes-frame).

    python3 elementor/scripts/frame_outline.py

Paste the output over the "Framed image or video" block in css/pes-global.css,
then run build.py.

The shape (from the approved sketch): big angled corners, and one wide recess in the
middle third of the top and bottom edges with short angled shoulders. Width follows the
column; height follows the image.

Every edge is horizontal, vertical or a fixed-size diagonal, so the outline can be
offset inwards exactly. That lets the border line, the dark gap and the clipped photo
stay parallel at any width or height.
"""
from math import hypot

T = 5            # border line thickness
GAP = 6          # dark gap between the line and the photo
CW, CH = 52, 28  # corner cut: across, down
R0, R1 = 1 / 3, 2 / 3  # recess spans the middle third of the width
SDX, D = 22, 18  # recess shoulder: across, depth

# Vertices clockwise from the top-left, as (fx, ax, fy, ay):
#   x = fx * width + ax px,  y = fy * height + ay px
SHAPE = [
    (0, 0, 0, CH), (0, CW, 0, 0),                          # top-left corner
    (R0, 0, 0, 0), (R0, SDX, 0, D),                        # top recess, left shoulder
    (R1, -SDX, 0, D), (R1, 0, 0, 0),                       # top recess, right shoulder
    (1, -CW, 0, 0), (1, 0, 0, CH),                         # top-right corner
    (1, 0, 1, -CH), (1, -CW, 1, 0),                        # bottom-right corner
    (R1, 0, 1, 0), (R1, -SDX, 1, -D),                      # bottom recess, right shoulder
    (R0, SDX, 1, -D), (R0, 0, 1, 0),                       # bottom recess, left shoulder
    (0, CW, 1, 0), (0, 0, 1, -CH),                         # bottom-left corner
]


def direction(a, b):
    """Unit direction of the edge a→b (every edge's direction is independent of size)."""
    if a[0] != b[0]:                       # spans part of the width: horizontal
        return (1.0 if b[0] > a[0] else -1.0), 0.0
    if a[2] != b[2]:                       # spans the height: vertical
        return 0.0, (1.0 if b[2] > a[2] else -1.0)
    dx, dy = b[1] - a[1], b[3] - a[3]      # fixed-size diagonal
    n = hypot(dx, dy)
    return dx / n, dy / n


def inward_offsets(d):
    """Offset (ox, oy) in px for each vertex when the outline moves d px inwards."""
    out = []
    n = len(SHAPE)
    for i in range(n):
        u = direction(SHAPE[i - 1], SHAPE[i])
        v = direction(SHAPE[i], SHAPE[(i + 1) % n])
        n1 = (-u[1], u[0])  # right-hand normal = inwards for a clockwise outline (y down)
        n2 = (-v[1], v[0])
        k = d / (1 + n1[0] * n2[0] + n1[1] * n2[1])
        out.append(((n1[0] + n2[0]) * k, (n1[1] + n2[1]) * k))
    return out


def coord(f, a, inset):
    """CSS length for a point at fraction f of the frame plus a px, measured in an
    element that sits `inset` px inside the frame on every side."""
    px = round(a + (2 * f - 1) * inset, 2)
    if f == 0:
        return f"{px:g}px"
    pct = f"{f * 100:.4g}%"
    if px == 0:
        return pct
    return f"calc({pct} {'+' if px > 0 else '-'} {abs(px):g}px)"


def polygon(d, inset):
    offs = inward_offsets(d)
    pts = []
    for (fx, ax, fy, ay), (ox, oy) in zip(SHAPE, offs):
        pts.append(f"{coord(fx, ax + ox, inset)} {coord(fy, ay + oy, inset)}")
    return "polygon(" + ", ".join(pts) + ")"


P = T + GAP  # the photo sits this far inside the frame box

print(f"""/* Framed image or video – the PES frame shape.
   Big angled corners and a wide recess in the middle third of the top and bottom edges.
   The width follows the column and the height follows the photo.
   pes-frame        – orange→gold gradient line
   pes-frame-blue   – navy line
   Works on Image and Video widgets. Generated by scripts/frame_outline.py
   (line {T}px, gap {GAP}px, corners {CW}×{CH}px, recess {D}px deep).            */
.elementor .pes-frame.elementor-widget {{
  position: relative;
  padding: {P}px;
  background: var(--pes-gradient);
  clip-path: {polygon(0, 0)};
}}
.elementor .pes-frame-blue.elementor-widget {{ background: var(--pes-navy); }}
.elementor .pes-frame.elementor-widget::before {{ /* dark gap inside the line */
  content: "";
  position: absolute;
  inset: 0;
  background: var(--pes-bg);
  clip-path: {polygon(T, 0)};
}}
.elementor .pes-frame.elementor-widget .elementor-widget-container,
.elementor .pes-frame.elementor-widget img,
.elementor .pes-frame.elementor-widget .elementor-wrapper {{ position: relative; }}
.elementor .pes-frame img,
.elementor .pes-frame .elementor-wrapper {{
  display: block;
  width: 100%;
  clip-path: {polygon(P, P)};
}}
.elementor .pes-frame img {{ height: auto; max-width: 100%; }}
""")
